function EEG = preprocess_eeg_forASR(EEG)
% Common average reference, then CleanLine at 60 Hz and at 120 Hz, before ASR (apply_asr.m).
    % common average reference
    EEG = pop_reref(EEG, []);

    % CleanLine line-noise removal, run once for each frequency
    cleanline_params = struct(...
        'bandwidth', 2, ...
        'SignalType', 'Channels', ...
        'ChanCompIndices', 1:EEG.nbchan, ...
        'ScanForLines', 1, ...
        'NormalizeSpectrum', 1, ...
        'LineAlpha', 0.01, ...
        'PaddingFactor', 2, ...
        'PlotFigures', 0);

    for freq = [60 120]
        cleanline_params.LineFrequencies = freq;
        EEG = pop_cleanline(EEG, cleanline_params);
    end
end
