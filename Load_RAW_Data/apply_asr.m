function EEG = apply_asr(EEG, k)    
    % 应用ASR
    % ASR重建模式
    EEG = clean_rawdata(EEG, ...
         'off', ...     % 某channel持續x秒以上平值沒變化則視為壞掉的channel並將該channel去除，通常是5秒
        [0.25 0.75], ...    % 高通滤波设置 保守：[0.25 0.75]
         'off', ...   % 保守：0.2; 可提高到0.4-0.6 通道相关性阈值：基于其他通道重建每个通道的数据，如果原始数据与重建数据相关性低于阈值，则认为该通道质量差
       'off', ...    % 工频干扰检测阈值
         k, ...      % 想保留更多數據可設置4-5，想更嚴格可降低至2，核心参数k，用于判断数据是否为伪迹。计算当前窗口数据相对于校准数据的方差比，如果超过这个阈值，就认为是伪迹
         'off');       %想更積極地修復偽迹，可以降低到0.1-0.2；如果想更保守，可以提高到0.4-0.5，窗口标准:判断某个时间窗口是否需要整个被拒绝。如果一个窗口中超过25%的通道被判定为受污染，说明这段数据可能有大范围的伪迹(如头动)
