%         0.45, ...        % 大幅降低通道相关性要求(从0.7降到0.45)
%         8, ...           % 放宽高频噪声检测标准
%         25, ...          % 使用非常保守的ASR设置(从20增加到25)
%         0.4);            % 放宽窗口标准(从0.3增加到0.4)
%     EEG = clean_rawdata(EEG, ...
%         5, ...     %     
